CREATE TABLE ccu_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    steam_app_id bigint NOT NULL CHECK (steam_app_id BETWEEN 1 AND 4294967295),
    observed_at timestamptz NOT NULL,
    source_rank integer NOT NULL CHECK (source_rank BETWEEN 1 AND 100),
    player_count integer NOT NULL CHECK (player_count >= 0),
    peak_player_count integer NOT NULL CHECK (peak_player_count >= 0),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    deleted_at timestamptz,
    UNIQUE (observed_at, steam_app_id),
    UNIQUE (observed_at, source_rank)
);
